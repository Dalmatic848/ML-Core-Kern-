def normalize_mineral_name(name: str) -> str:
    """CSV хранит имена с пробелами ('Глина аргиллитоподобная'); имена тайлов
    и MINERAL_TO_CLASS используют подчёркивания. Единая точка нормализации."""
    return name.strip().replace(" ", "_")


def mineral_to_class(mineral: str) -> Optional[str]:
    """Класс для нормализованного имени минерала, либо None если минерал
    неизвестен или явно исключён из таксономии."""
    return MINERAL_TO_CLASS.get(normalize_mineral_name(mineral))


# ── Soft labels: 5 базовых компонент ──────────────────────────────────────────

def load_soft_labels_config(path: Path = SOFT_LABELS_CONFIG_PATH) -> Tuple[List[str], Dict[str, List[float]]]:
    """Возвращает (base_classes, mineral -> soft-label vector).
    Ключи soft-label словаря нормализованы (пробелы → подчёркивания)."""
    with open(path, encoding="utf-8") as f:
        cfg = json.load(f)
    base_classes = cfg["_base_classes"]
    soft_map = {normalize_mineral_name(k): v for k, v in cfg["minerals"].items()}
    return base_classes, soft_map


def validate_taxonomy(path: Path = SOFT_LABELS_CONFIG_PATH, tol: float = 1e-6) -> None:
    """Проверяет целостность таксономии. Бросает AssertionError с понятным
    сообщением при первом нарушении:
      1. Каждый soft-label вектор имеет длину len(base_classes).
      2. Каждый soft-label вектор суммируется в 1.0 (± tol).
      3. Все значения в векторе неотрицательны.
      4. Каждый минерал из soft_labels_config.json, для которого также есть
         запись в MINERAL_TO_CLASS, не помечен там как None (иначе он не
         может одновременно участвовать в hard- и soft-label датасетах).
    """
    base_classes, soft_map = load_soft_labels_config(path)
    n = len(base_classes)

    for mineral, vec in soft_map.items():
        if len(vec) != n:
            raise AssertionError(
                f"{mineral!r}: длина вектора {len(vec)} != {n} (base_classes={base_classes})"
            )
        if any(v < 0 for v in vec):
            raise AssertionError(f"{mineral!r}: отрицательная доля в векторе {vec}")
        total = sum(vec)
        if abs(total - 1.0) > tol:
            raise AssertionError(f"{mineral!r}: вектор {vec} суммируется в {total}, ожидалось 1.0")

        hard_class = MINERAL_TO_CLASS.get(mineral)
        if mineral in MINERAL_TO_CLASS and hard_class is None:
            raise AssertionError(
                f"{mineral!r} исключён в MINERAL_TO_CLASS (None), "
                f"но присутствует в soft_labels_config.json"
            )


if __name__ == "__main__":
    validate_taxonomy()
    print(f"OK: {len(MINERAL_TO_CLASS)} минералов → {len(CLASSES_ORDER)} классов; "
          f"{len(load_soft_labels_config()[1])} soft-label записей валидны.")
